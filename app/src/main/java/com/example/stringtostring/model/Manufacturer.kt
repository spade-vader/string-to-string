package com.example.stringtostring.model

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * Представление производителя ниток в базе данных.
 *
 * Использование:
 * - Является частью слоя данных (data layer) архитектуры приложения.
 * - Хранение информации о производителе ниток, участвующем в цветовых соответствиях.
 *
 * Хранилище:
 * - Таблица "manufacturers" в SQLite базе данных через Room ORM.
 *
 * Поля:
 * @property id Уникальный идентификатор производителя. Используется как первичный ключ. Генерация осуществляется автоматически.
 * @property name Название производителя (например, "DMC", "Gamma" и т.д.).
 *
 * Связи:
 * - Может использоваться в качестве внешнего ключа в таблице ниток (например, в таблице "threads").
 *
 * Примечания:
 * - Идентификатор не должен передаваться вручную при создании нового экземпляра, если используется автоинкремент.
 * - Допускается хранение нескольких производителей с уникальными именами.
 */
@Entity(tableName = "manufacturers")
data class Manufacturer(
    @PrimaryKey(autoGenerate = true) val id: Int,
    val name: String
)
